# ------------------------------------------------------------
# 独立评测集（holdout）
# ------------------------------------------------------------
# 面试官会问"评测样本是否独立于调参样本"。做法：
#   抽 20% 作为 holdout，调参只碰 dev 集；最终指标只在 holdout 上报告。
#
# 两个容易踩的坑，这里都躲开了：
#   1) 不能用索引切分（i % 5 == 0）。
#      往题库中间插一道题，后面所有题的索引整体后移，holdout 集合全变，
#      昨天报告的成绩今天就复现不出来。这里改用题面哈希排序，题面不变则归属不变。
#   2) 不能纯随机抽。
#      题库是按主题分段写的，纯随机会让某些知识块一道题都没进 holdout
#      （实测 13/39 个块完全没被覆盖），holdout 就代表不了全库。
#      这里按知识块分层抽，每块至少 1 题。
import hashlib

HOLDOUT_RATIO = 20          # 百分比


def _group_key(item):
    """跨块题按第一个期望块归组，陷阱题单独一组。"""
    e = item["expect"]
    if e == "（无）":
        return "（无）"
    return e if isinstance(e, str) else e[0]


def _pick_holdout(items):
    """先按题型定额，层内按块轮转，最后补漏保证每块至少 1 题。

    只按块分层会让稀有题型被淹没（跨块题只有 22 道，散在各块里，
    轮不到就被普通题挤光）。所以先按 difficulty 分配合额，
    再在层内轮转，让每块都有机会先出 1 题。
    """
    by_diff = {}
    for it in items:
        by_diff.setdefault(it.get("difficulty", "normal"), []).append(it)

    picked = set()
    for group in by_diff.values():
        quota = max(1, round(len(group) * HOLDOUT_RATIO / 100.0))

        by_block = {}
        for it in group:
            by_block.setdefault(_group_key(it), []).append(it)
        for blk in by_block:
            by_block[blk].sort(key=lambda it: hashlib.md5(
                it["q"].encode("utf-8")).hexdigest())

        blocks = sorted(by_block)        # 固定顺序，保证可复现
        depth = max(len(v) for v in by_block.values())
        order = []
        for d in range(depth):
            for b in blocks:             # 轮转：每块先各出 1 题，再出第 2 轮
                if d < len(by_block[b]):
                    order.append(by_block[b][d]["q"])

        for q in order[:quota]:
            picked.add(q)

    # 补漏：某些块题太少、配额不够时可能一道都没抽到。
    # 按哈希取该块第一道，而不是按文件顺序 —— 文件开头集中放着示例题，
    # 按顺序补会把 L1 全补进 holdout，层次分布直接歪掉（实测 L1 曾占 38%）。
    covered = {_group_key(it) for it in items if it["q"] in picked}
    by_block_all = {}
    for it in items:
        by_block_all.setdefault(_group_key(it), []).append(it)
    for blk in sorted(by_block_all):
        if blk in covered:
            continue
        cands = sorted(by_block_all[blk], key=lambda it: hashlib.md5(
            it["q"].encode("utf-8")).hexdigest())
        picked.add(cands[0]["q"])
        covered.add(blk)

    return picked


_HOLDOUT_TEXT = _pick_holdout(QUESTIONS)

# 保留索引形式，兼容可能已有引用
